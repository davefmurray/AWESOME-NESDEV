#!/usr/bin/env python3
"""Generate a starting BZK 6502 config.lua from an iNES/NES 2.0 ROM.

This does not simulate runtime banking. It proposes static windows:
NROM/CNROM fixed, UxROM/MMC1 16K switchable + fixed high bank, MMC3 8K
switchable + fixed last two, AxROM 32K. Verify with the CDL data-mapping
flags and duplicate windows manually when code runs in more than one slot.

Usage:
    python3 bzk_config.py game.nes --cdl game.cdl --out config.lua
"""

from __future__ import annotations
import argparse, os, sys

def num(s: str) -> int:
    return int(s, 0)

def parse(path: str) -> dict:
    b = open(path, "rb").read()
    if b[:4] != b"NES\x1a":
        raise SystemExit(f"{path}: not an iNES/NES 2.0 file")
    f6, f7 = b[6], b[7]
    nes2 = (f7 & 0x0C) == 0x08
    prg_lo, chr_lo = b[4], b[5]
    if nes2:
        exp = (f7 & 0x03) << 8 | b[9]
        pu = prg_lo | ((b[9] & 0x0F) << 8)
        cu = chr_lo | ((b[9] & 0xF0) << 4)
        prg = pu * 16384 if exp == 0 else pu * (1 << exp)
        chr = cu * 8192 if exp == 0 else cu * (1 << exp)
    else:
        prg, chr = prg_lo * 16384, chr_lo * 8192
    mapper = (f7 & 0xF0) | (f6 >> 4)
    if nes2:
        mapper |= (b[8] & 0x0F) << 8
    return {"prg": prg, "chr": chr, "mapper": mapper, "nes2": nes2}

def entries(info: dict, table: str) -> list[tuple[str, int, int, int, str]]:
    prg, m = info["prg"], info["mapper"]
    t = f'"{table}"' if table else "false"
    out = []
    if m in (0, 3):
        if prg == 0x8000:
            out.append(("bank_00.asm", 0x10, 0x8000, 0x8000, t))
        elif prg == 0x4000:
            out.append(("bank_00.asm", 0x10, 0xC000, 0x4000, t))
        else:
            raise SystemExit(f"mapper {m}: unsupported PRG size 0x{prg:X}")
    elif m in (1, 2):
        if prg % 0x4000:
            raise SystemExit(f"mapper {m}: PRG 0x{prg:X} is not a multiple of 16K")
        n = prg // 0x4000
        for i in range(n - 1):
            out.append((f"bank_{i:02X}.asm", 0x10 + i * 0x4000, 0x8000, 0x4000, t))
        out.append(("bank_fixed.asm", 0x10 + (n - 1) * 0x4000, 0xC000, 0x4000, t))
    elif m == 4:
        if prg % 0x2000:
            raise SystemExit(f"mapper 4: PRG 0x{prg:X} is not a multiple of 8K")
        n = prg // 0x2000
        for i in range(max(0, n - 2)):
            out.append((f"bank_{i:02X}.asm", 0x10 + i * 0x2000, 0x8000, 0x2000, t))
        if n >= 2:
            out.append(("bank_C000.asm", 0x10 + (n - 2) * 0x2000, 0xC000, 0x2000, t))
            out.append(("bank_E000.asm", 0x10 + (n - 1) * 0x2000, 0xE000, 0x2000, t))
    elif m == 7:
        if prg != 0x8000:
            raise SystemExit(f"mapper 7: expected 32K PRG, got 0x{prg:X}")
        out.append(("bank_00.asm", 0x10, 0x8000, 0x8000, t))
    else:
        raise SystemExit(f"mapper {m}: no template; add ASM_config_table entries manually")
    return out

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("rom")
    ap.add_argument("--cdl", default="game.cdl")
    ap.add_argument("--table", default=None, help="optional .tbl text table")
    ap.add_argument("--ram-file", default="bank_ram.inc")
    ap.add_argument("--out", help="write config.lua (default stdout)")
    a = ap.parse_args(argv)
    info = parse(a.rom)
    rows = entries(info, a.table)
    rom_name = os.path.basename(a.rom)
    cdl_name = os.path.basename(a.cdl)
    lines = []
    lines.append("-- Generated by bzk_config.py; verify bank windows against the CDL D flag.")
    lines.append(f"-- ROM: {a.rom}  mapper {info['mapper']}  PRG 0x{info['prg']:X}  CHR 0x{info['chr']:X}")
    lines.append('INPUT_folder = "C:/BZK 6502/input/"')
    lines.append('OUTPUT_folder = "C:/BZK 6502/output/"')
    lines.append(f'ROM_file = "{rom_name}"')
    lines.append(f'CDL_file = "{cdl_name}"')
    lines.append('HEADER_file = { "header.bin", 0x000000, 0x10 }')
    if info["chr"]:
        lines.append(f'CHR_file = {{ "CHR_ROM.chr", 0x{0x10 + info["prg"]:06X}, 0x{info["chr"]:X} }}')
    else:
        lines.append('CHR_file = { "CHR_ROM.chr", 0x000000, 0x0 }')
    lines.append(f'RAM_file = "{a.ram_file}"')
    lines.append("DEBUG_file = { \"debug.txt\", true }")
    lines.append("FORCE_byte_comments = true")
    lines.append("")
    lines.append("ASM_config_table =")
    lines.append("    {--       1            2        3       4        5")
    for name, off, cpu, size, tbl in rows:
        lines.append(f'        "{name}", 0x{off:06X}, 0x{cpu:04X}, 0x{size:04X}, {tbl},')
    lines.append("    }")
    text = "\n".join(lines) + "\n"
    if a.out:
        open(a.out, "w").write(text)
        print(f"wrote {a.out}: {len(rows)} bank entries, mapper {info['mapper']}")
    else:
        print(text)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
